/**
 * docs/06: the Windows client is a **Desktop** OAuth client, whose `client_secret` Google's own
 * documentation says is not a secret — but it is per-developer, so it is never committed (README).
 * Order: `local.properties`, then the environment, then a placeholder that keeps the build green
 * and only makes sign-in fail (the phone does the same, `android/app/build.gradle.kts`).
 */
val localProperties: Properties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}

fun oauth(key: String, env: String, fallback: String): String =
    localProperties.getProperty(key) ?: System.getenv(env) ?: fallback

version = "0.0.1-dev"

/**
 * `BuildConfig` by hand: one generated object, so the ids are compiled in rather than read off a
 * file the packaged app would have to carry.
 */
val generateOAuthConfig = tasks.register("generateOAuthConfig") {
    val clientId = oauth("google.desktopClientId", "REC_GOOGLE_DESKTOP_CLIENT_ID", "REPLACE_ME.apps.googleusercontent.com")
    val clientSecret = oauth("google.desktopClientSecret", "REC_GOOGLE_DESKTOP_CLIENT_SECRET", "REPLACE_ME")
    val version = project.version.toString()
    val output = layout.buildDirectory.dir("generated/oauth")
    inputs.property("clientId", clientId)
    inputs.property("clientSecret", clientSecret)
    inputs.property("version", version)
    outputs.dir(output)
    doLast {
        val file = output.get().file("app/recly/windows/auth/OAuthConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            // Generated by :windows:app:generateOAuthConfig — do not edit.
            package app.recly.windows.auth

            object OAuthConfig {
                const val CLIENT_ID: String = "$clientId"
                const val CLIENT_SECRET: String = "$clientSecret"
                const val APP_VERSION: String = "$version"

                /** True while the placeholders are in place: sign-in is offered but cannot work. */
                val isPlaceholder: Boolean get() = CLIENT_ID.startsWith("REPLACE_ME")
            }

            """.trimIndent(),
        )
    }
}

