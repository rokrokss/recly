compose.desktop {
    application {
        mainClass = "app.recly.windows.MainKt"

        nativeDistributions {
            /**
             * docs/14 "앱": the MSI carries the capture helper and — ADR-019 — an LGPL ffmpeg next
             * to it. jpackage copies the platform's subdirectory into the installed app and hands
             * the app its path in `compose.application.resources.dir`, which is where
             * `CaptureHelper.command()` looks. `.github/workflows/windows.yml` is what puts the two
             * binaries in `resources/windows-x64` before `packageMsi`; the directory is otherwise
             * empty in git (`windows/README.md`).
             */
            appResourcesRootDir.set(project.layout.projectDirectory.dir("resources"))

            // MSI is the Windows target (docs/14 N7); the DMG is what this development machine can
            // actually build and is how `packageDistributionForCurrentOS` is verified here.
            targetFormats(TargetFormat.Msi, TargetFormat.Dmg)

            // jpackage ships a runtime with only the modules named here, and a missing one is a
            // crash at startup rather than a build error. `java.sql` is SQLDelight's JDBC driver
            // (found the hard way: the packaged app died on `java.sql.DriverManager`); `java.naming`
            // and `jdk.crypto.ec` are what TLS needs for Drive; `jdk.unsupported` is JNA's.
            modules("java.sql", "java.naming", "jdk.crypto.ec", "jdk.unsupported")
            packageName = "Recly"
            packageVersion = version.toString().substringBefore('-') // MSI wants MAJOR.MINOR.BUILD
            vendor = "Recly"
            description = "Recly — record and run workflows"

            // docs/09 "앱 아이콘": one master, per-platform exports. jpackage wants a different
            // container per platform, and all three are written by `scripts/render-icons.swift`.
            val icons = project.layout.projectDirectory.dir("src/main/icons")

            windows {
                iconFile.set(icons.file("recly.ico"))
                menu = true
                menuGroup = "Recly"
                // A desktop shortcut, and a chance to say where it goes: this is a tray app, and an
                // install with no icon anywhere is one nobody finds again.
                shortcut = true
                dirChooser = true
                // `%LOCALAPPDATA%` is where the data lives (`Host.dataDir`) and HKCU is where the
                // Run key does (`WindowsRunKey`): a per-user install needs no elevation and matches
                // both. docs/14 "앱": launch at login stays the app's own setting — an MSI cannot
                // write a Run key that the user can then turn off from the tray.
                perUserInstall = true
                // Stable across releases so an upgrade replaces the install rather than adding one.
                upgradeUuid = "6f3a1f2e-9b64-4a4e-9f0d-2a0c9a1d5b71"
            }
            linux {
                iconFile.set(icons.file("recly.png"))
            }
            macOS {
                iconFile.set(icons.file("recly.icns"))
                bundleID = "app.recly.windows"
                // macOS refuses a major version of 0, and this bundle is only ever the development
                // host's build of a Windows app (M6-L1 "환경 제약") — the shipped version is the
                // project's, which is what `OAuthConfig.APP_VERSION` and the MSI carry.
                packageVersion = "1.0.0"
            }
        }
    }
}
